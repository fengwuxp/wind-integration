package com.wind.integration.metrics.repository;

import com.wind.integration.metrics.query.MetricQuery;
import com.wind.integration.metrics.spec.MetricDefinitionObject;
import org.jspecify.annotations.NonNull;

/**
 * 实时指标数据访问的业务扩展接口，隔离具体业务方的数据源访问和结果映射。
 *
 * <p>Wind 声明共同读取约定，由宿主实现实际数据访问。Realtime 对应 REALTIME 数据来源，
 * 表示按本次条件查询事实数据，不承诺数据零延迟；读取可见性仍取决于事实数据及当前事务视图。
 * 本接口与 {@link MetricSnapshotRepository} 同属数据访问扩展边界，分别承担实时读取与完整快照读写。</p>
 *
 * <h2>输入与结果对象</h2>
 * <p>输入是已经选定精确编码与修订的 RAW 定义，以及主体、完整维度、实际时间范围和声明参数。
 * T 是调用方与实现约定的完整实时结果对象，可以是业务 DTO、record 或 Map；泛型本身不规定
 * 物理字段、对象结构或存储方式，不能只凭 T 相同就认定不同实现可互换。</p>
 * <ul>
 * <li>DSL 定义：返回本次事实查询的完整基础统计量，即 measure 结果；字段集合与编译投影一致，
 * 留给上层合并后计算表达式、最终精度和缺省值。</li>
 * <li>SQL 定义：返回 SQL 已计算的结果列，并保留其逻辑名称、类型及正常空值；不能把这些列
 * 自动解释为可累计的原始状态。</li>
 * </ul>
 * <p>例如订单统计可以一次返回数量和金额，宿主将其表示为业务对象或具名字段 Map。
 * 返回对象本身非空；字段正常为空与缺失字段、读取失败应明确区分。</p>
 *
 * <h2>职责边界</h2>
 * <p>实现负责将定义与条件转换为受支持的数据访问，执行查询并校验结果结构和类型。
 * JDBC 实现可以组合现有 SQL 编译或模板渲染能力，承担参数绑定、超时、执行和结果映射；
 * SUM、COUNT 等统计可以在数据源查询中完成。指标选版、依赖展开、分段编排、跨段合并、
 * 指标累计以及 DSL 最终类型归一化、舍入、表达式和缺省值处理仍由上层承担。</p>
 * <p>数据源、冻结物理绑定及超时由实现装配，不作为查询参数传递。实现复用宿主当前事务，
 * 不另开依赖查询事务，不读取快照或执行物化；不支持的定义或条件应明确失败，不能丢弃条件、
 * 改选版本或改用其他来源继续执行。</p>
 * <p>SQL SCALAR 要求一行一列，逻辑字段为 value；FIELD_SET 要求一行、至少一列，
 * 采用非空且唯一的列标签。列类型由 JDBC 元数据确定，NULL 也须保留明确类型；
 * 无法确定或不支持的类型、零行、多行、重复列均明确失败。事实集合为空时，聚合查询仍可能
 * 返回一行 COUNT=0 或其他正常 NULL；不能将这种正常结果与没有结果行混为一谈。</p>
 *
 * <h2>使用场景与接入建议</h2>
 * <ul>
 * <li>实时查询：按已选定定义和本次条件读取完整结果，交给查询服务完成后续计算。</li>
 * <li>分段查询：只执行上层已经确定实际起止时间的实时段，不自行计算快照水位或决定段间衔接。</li>
 * <li>物化中的事实读取：上层确定本次增量窗口后复用读取能力，仓储不合并旧快照、不保存结果或推进水位。</li>
 * </ul>
 * <p>建议在宿主装配位置选择实现，业务流程依赖本接口，并明确 T 的字段、类型和空值约定。
 * 多次 query 是否共享一致读取视图由上层事务边界保障，接口不会自动创建批级事务或缓存。</p>
 * <p>建议用真实数据访问测试验证主体与维度隔离、时间边界、声明参数、字段完整性、类型精度、
 * 正常空值、异常和事务可见性；接口泛型测试只证明对象可以传递，不能替代具体数据源的执行验证。</p>
 *
 * @param <T> 调用方与具体仓储约定的完整实时结果对象类型
 * @author wuxp
 * @since 2026-09-23
 */
@FunctionalInterface
public interface MetricRealtimeRepository<T> {

    /**
     * 按精确定义和本次查询条件读取一个完整实时结果对象。
     *
     * <p>实现须遵守定义与条件的适用约束，保留完整结果和正常字段空值；错误继续传播，
     * 不能返回部分字段、用零值掩盖失败或用 null 对象表示查询失败。</p>
     *
     * @param definition 已选定精确编码与修订的 RAW DSL 或 SQL 定义
     * @param query 主体、维度、实际时间范围及业务参数；条件语义由宿主依定义校验
     * @return 完整实时结果对象；对象本身不得为 null，内部字段的空值语义由 T 的契约定义
     * @throws RuntimeException 定义或条件不支持、结果结构/类型不合法，或数据访问失败
     */
    @NonNull T query(@NonNull MetricDefinitionObject definition, @NonNull MetricQuery query);
}
